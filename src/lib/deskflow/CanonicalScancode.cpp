std::optional<uint16_t> macVirtualKeyFromSet1(KeyButton scancode)
{
  const auto i = std::ranges::find(kEntries, scancode, &Entry::m_set1);
  return i == kEntries.end() ? std::nullopt : std::optional<uint16_t>(i->m_macVirtualKey);
}

std::optional<KeyButton> set1FromMacVirtualKey(uint16_t virtualKey)
{
  const auto i = std::ranges::find(kEntries, virtualKey, &Entry::m_macVirtualKey);
  return i == kEntries.end() ? std::nullopt : std::optional<KeyButton>(i->m_set1);
}

bool isSet1Scancode(KeyButton scancode)
{
  // One byte of Set-1, optionally with the 0xe0 extended prefix folded into bit 8.
  return scancode != 0 && (scancode & ~static_cast<KeyButton>(0x1ff)) == 0 && (scancode & 0xffu) != 0;
}

